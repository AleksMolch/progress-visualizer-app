/**
 * Назначение: модель метаданных фотографии прогресса.
 *
 * Функции:
 * - описывает метаданные одного снимка, привязанного к проекту.
 * - хранит ссылку на файл фото, но НЕ сам файл (файл лежит в sandbox).
 *
 * Слой: model (/src/models). Чистый тип без логики и зависимостей.
 */

export interface PhotoMetadata {
  /** Уникальный идентификатор записи метаданных. */
  id: string;
  /** Идентификатор проекта, к которому относится снимок. */
  projectId: string;
  /** Путь к файлу фото внутри sandbox приложения. */
  uri: string;
  /** Метка времени съёмки (epoch ms). */
  takenAt: number;
  /** Ширина изображения в пикселях (необязательно). */
  width?: number;
  /** Высота изображения в пикселях (необязательно). */
  height?: number;
}
